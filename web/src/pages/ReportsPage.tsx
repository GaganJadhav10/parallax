import React, { useEffect, useState } from 'react';
import {
  FileText,
  FileCode,
  ExternalLink,
  Download,
  Clock,
  Search,
  RefreshCw,
} from 'lucide-react';
import { api } from '../services/api';
import { ScanRecord } from '../types';
import { StatusBadge } from '../components/StatusBadge';

export const ReportsPage: React.FC = () => {
  const [scans, setScans] = useState<ScanRecord[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [filter, setFilter] = useState<string>('');

  const loadScans = async () => {
    setLoading(true);
    try {
      const records = await api.getScans({ limit: 100 });
      setScans(records);
    } catch (err: unknown) {
      console.error('Failed to load scans for reports:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadScans();
  }, []);

  const filteredScans = scans.filter((s) =>
    s.target.toLowerCase().includes(filter.toLowerCase()) ||
    s.id.toLowerCase().includes(filter.toLowerCase())
  );

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-white tracking-tight flex items-center gap-2">
            <FileText className="w-6 h-6 text-primary" />
            <span>Reconnaissance Intelligence Reports</span>
          </h1>
          <p className="mt-1 text-xs sm:text-sm text-slate-400">
            Export standalone offline HTML intelligence reports or raw JSON structures.
          </p>
        </div>

        {/* Filter */}
        <div className="flex items-center gap-2">
          <div className="relative">
            <Search className="w-3.5 h-3.5 absolute left-3 top-2.5 text-slate-400" />
            <input
              type="text"
              placeholder="Search target domain..."
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
              className="pl-8 pr-3 py-1.5 bg-slate-900 border border-surface-border rounded-lg text-xs text-white placeholder-slate-500 focus:outline-none focus:ring-1 focus:ring-primary font-mono w-48 sm:w-56"
            />
          </div>
          <button
            onClick={loadScans}
            className="p-2 text-slate-400 hover:text-white bg-slate-900 border border-surface-border rounded-lg text-xs transition-colors"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          </button>
        </div>
      </div>

      {/* Info card */}
      <div className="p-4 rounded-xl bg-surface border border-surface-border text-xs text-slate-300 flex items-start gap-3">
        <FileText className="w-5 h-5 text-primary shrink-0 mt-0.5" />
        <div>
          <p className="font-semibold text-white">Standalone Offline Reports</p>
          <p className="text-slate-400 mt-0.5 leading-relaxed">
            HTML reports generated by ReconLens are completely self-contained with embedded stylesheets and require zero internet connection or external CDN dependencies to view.
          </p>
        </div>
      </div>

      {/* Reports Table Card */}
      <div className="bg-surface border border-surface-border rounded-xl overflow-hidden shadow-xl">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-900/60 text-slate-400 uppercase font-medium tracking-wider text-[11px] border-b border-surface-border">
              <tr>
                <th className="py-3 px-4">Target Domain</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-4">Findings</th>
                <th className="py-3 px-4">Date</th>
                <th className="py-3 px-4 text-right">Export Options</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-surface-border">
              {loading ? (
                <tr>
                  <td colSpan={5} className="py-12 text-center text-slate-400">
                    <RefreshCw className="w-5 h-5 animate-spin mx-auto mb-2 text-primary" />
                    Loading report catalog...
                  </td>
                </tr>
              ) : filteredScans.length === 0 ? (
                <tr>
                  <td colSpan={5} className="py-12 text-center text-slate-400">
                    No scan records available to export.
                  </td>
                </tr>
              ) : (
                filteredScans.map((scan) => (
                  <tr key={scan.id} className="hover:bg-slate-800/30 transition-colors">
                    <td className="py-3 px-4 font-mono font-medium text-white">
                      <span>{scan.target}</span>
                      <span className="block text-[10px] text-slate-500 font-normal">
                        ID: {scan.id.slice(0, 8)}...
                      </span>
                    </td>
                    <td className="py-3 px-4">
                      <StatusBadge status={scan.status} size="sm" />
                    </td>
                    <td className="py-3 px-4 font-mono text-slate-300 font-semibold">
                      {scan.final_subdomains || 0}
                    </td>
                    <td className="py-3 px-4 text-slate-400 text-[11px]">
                      <div className="flex items-center gap-1.5">
                        <Clock className="w-3 h-3 text-slate-500" />
                        {new Date(scan.started_at).toLocaleString()}
                      </div>
                    </td>
                    <td className="py-3 px-4 text-right">
                      <div className="flex items-center justify-end gap-2">
                        {/* HTML Report Link */}
                        <a
                          href={api.getReportURL(scan.id, 'html')}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium border border-surface-border transition-colors"
                          title="Open HTML report in new tab"
                        >
                          <FileText className="w-3.5 h-3.5 text-primary" />
                          <span>View HTML Report</span>
                          <ExternalLink className="w-3 h-3 text-slate-500" />
                        </a>

                        {/* JSON Report Link */}
                        <a
                          href={api.getReportURL(scan.id, 'json')}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium border border-surface-border transition-colors"
                          title="Open JSON report in new tab"
                        >
                          <FileCode className="w-3.5 h-3.5 text-amber-400" />
                          <span>View JSON</span>
                          <ExternalLink className="w-3 h-3 text-slate-500" />
                        </a>
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
